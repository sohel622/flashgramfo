-- 4. Database Trigger: handle_new_user()
-- Automatically creates a profile record when a new user signs up via Google OAuth or Email
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
DECLARE
  v_name TEXT;
  v_avatar TEXT;
  v_handle TEXT;
  v_email TEXT;
BEGIN
  v_email := NEW.email;
  v_name := COALESCE(
    NEW.raw_user_meta_data->>'full_name',
    NEW.raw_user_meta_data->>'name',
    NEW.raw_user_meta_data->>'display_name',
    split_part(v_email, '@', 1)
  );
  v_avatar := COALESCE(
    NEW.raw_user_meta_data->>'avatar_url',
    NEW.raw_user_meta_data->>'picture'
  );
  v_handle := lower(regexp_replace(COALESCE(split_part(v_email, '@', 1), v_name), '[^a-zA-Z0-9_]', '', 'g'));
  IF length(v_handle) < 3 THEN
    v_handle := 'creator_' || substr(md5(NEW.id::text), 1, 6);
  END IF;

  INSERT INTO public.profiles (user_id, display_name, full_name, username, email, avatar_url, updated_at)
  VALUES (
    NEW.id,
    v_name,
    v_name,
    v_handle,
    v_email,
    v_avatar,
    timezone('utc'::text, now())
  )
  ON CONFLICT (user_id) DO UPDATE
  SET
    display_name = COALESCE(public.profiles.display_name, EXCLUDED.display_name),
    full_name = COALESCE(public.profiles.full_name, EXCLUDED.full_name),
    avatar_url = COALESCE(public.profiles.avatar_url, EXCLUDED.avatar_url),
    email = COALESCE(public.profiles.email, EXCLUDED.email),
    updated_at = timezone('utc'::text, now());

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

