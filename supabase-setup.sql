DROP TRIGGER IF EXISTS trg_comments_fill_owner ON public.comments;
CREATE TRIGGER trg_comments_fill_owner
  BEFORE INSERT ON public.comments
  FOR EACH ROW
  EXECUTE FUNCTION public.fill_post_owner_id();

